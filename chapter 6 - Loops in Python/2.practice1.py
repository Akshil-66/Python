# Print numbers from 1 to 10 using while loop.

num = 1

print("Forward Order :- ")

while (num<=10):  # we can also write condition in bracket or without bracket
    print(num)
    num += 1

# Print numbers from 10 to 1 using while loop.

i=10

print("Reverse Order :- ")

while i>=1:
    print(i)
    i-=1