# Arithmetic operators

x=10
y=5

print("Addition is :- " , x+y )
print("Differance is :-" , x-y)
print("Multiplication is :-" , x*y)
print("Division is :-" , x/y)
print("Modulus is :-" , x%y)
print("Exponent is :-" , x**y)

#comparison operators

print("Is x and y are equal :-" , x==y)
print("Is x greater than y :- " , x>y)
print("Is x is less than y:- " , x<y)

#logical operators

print("And operator for x>y and x<y :- " , x>y and x<y)
print("Or operator for x>y and x<y :- " , x>y or x<y)
print("Not operator for x>y :-" , not(x>y) )

